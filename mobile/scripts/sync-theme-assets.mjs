// sync-theme-assets.mjs — generate the mobile-local theme asset registry.
//
// Metro requires STATIC `require()` calls, so an RN image cannot be loaded from
// a runtime path string (`theme.assets[slot]`). This script bridges the gap:
// for EVERY shipped theme directory under `web/public/themes/` it
//
//   1. copies each `<file>.png` to `mobile/assets/themes/<name>/<file>.png`, and
//   2. emits `mobile/src/themeAssets.gen.ts` with one literal `require()` per PNG,
//      keyed `` `<name>/<file>.png` ``, embedding the pixel width/height measured
//      from each PNG's own IHDR header — not hard-coded, and without importing
//      `ASSET_SLOTS` (which the engine deliberately does not export).
//
// Dependency-free Node ESM (`node:fs` + `node:path`), idempotent: a second run
// rewrites byte-identical outputs, so `git status` only changes on a real change.
//
// Usage (from the repo root):
//     node mobile/scripts/sync-theme-assets.mjs
//
// Source of truth for the file set is the PNGs on disk; the runtime theme map is
// validated against this registry by a Jest test, so a stale registry fails
// loudly in CI.

import { copyFileSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Repo root, resolved from this script's URL (`mobile/scripts/` → repo). */
const repoRoot = fileURLToPath(new URL('../../', import.meta.url));
const sourceRoot = join(repoRoot, 'web', 'public', 'themes');
const destRoot = join(repoRoot, 'mobile', 'assets', 'themes');
const registryPath = join(repoRoot, 'mobile', 'src', 'themeAssets.gen.ts');

/** The 8-byte PNG signature: `89 50 4E 47 0D 0A 1A 0A`. */
const PNG_SIGNATURE = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

/**
 * Read a PNG's pixel size from its IHDR header (signature + IHDR chunk: width
 * big-endian uint32 at byte 16, height at byte 20). Throws when the file is not
 * a PNG or is too short, so a bad input fails the sync rather than emitting a
 * bogus registry entry.
 */
function readPngDimensions(bytes) {
  if (bytes.length < 24) {
    throw new Error(`not a PNG: buffer is ${bytes.length} bytes (< 24)`);
  }
  if (!bytes.subarray(0, 8).equals(PNG_SIGNATURE)) {
    throw new Error('not a PNG: bad signature');
  }
  if (bytes.toString('latin1', 12, 16) !== 'IHDR') {
    throw new Error('not a PNG: missing IHDR chunk');
  }
  return { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) };
}

/** Sorted `.png` file names in a directory (deterministic registry order). */
function pngFilesIn(dir) {
  return readdirSync(dir)
    .filter((name) => name.endsWith('.png'))
    .sort();
}

/** Sorted theme directory names under `web/public/themes/`. */
function themeDirs() {
  return readdirSync(sourceRoot)
    .filter((name) => statSync(join(sourceRoot, name)).isDirectory())
    .sort();
}

/**
 * The generated file's literal `require()` argument, relative to the file that
 * contains it. The registry is `mobile/src/themeAssets.gen.ts`, so `../assets`
 * resolves to `mobile/assets/` (one level up from `src/`).
 */
function requirePath(themeName, fileName) {
  return `../assets/themes/${themeName}/${fileName}`;
}

function main() {
  if (!statSync(sourceRoot).isDirectory()) {
    throw new Error(`theme source directory not found: ${sourceRoot}`);
  }

  const themes = themeDirs();
  /** @type {Array<{ themeName: string; fileName: string; width: number; height: number }>} */
  const entries = [];

  for (const themeName of themes) {
    const srcDir = join(sourceRoot, themeName);
    const destDir = join(destRoot, themeName);
    mkdirSync(destDir, { recursive: true });

    const files = pngFilesIn(srcDir);
    for (const fileName of files) {
      const srcPath = join(srcDir, fileName);
      const destPath = join(destDir, fileName);
      const bytes = readFileSync(srcPath);
      const { width, height } = readPngDimensions(bytes);
      copyFileSync(srcPath, destPath);
      entries.push({ themeName, fileName, width, height });
    }
    console.log(`  ${themeName}: ${files.length} PNGs → ${destDir}`);
  }

  const lines = [];
  lines.push('// themeAssets.gen.ts — GENERATED by mobile/scripts/sync-theme-assets.mjs.');
  lines.push('//');
  lines.push('// Do not edit by hand: run `npm run mobile:assets` to regenerate. One literal');
  lines.push('// `require()` per bundled theme PNG (Metro resolves static requires only), with');
  lines.push('// the pixel size measured from each PNG\'s IHDR header. Keyed');
  lines.push("// `<theme-name>/<file>` — the exact lookup `resolveAsset` performs.");
  lines.push('');
  lines.push("import type { ImageSourcePropType } from 'react-native';");
  lines.push('');
  lines.push('export interface ThemeAssetSource {');
  lines.push('  /** The bundled image module Metro resolves from the literal require. */');
  lines.push('  source: ImageSourcePropType;');
  lines.push('  /** Pixel width measured from the PNG\'s IHDR header. */');
  lines.push('  width: number;');
  lines.push('  /** Pixel height measured from the PNG\'s IHDR header. */');
  lines.push('  height: number;');
  lines.push('}');
  lines.push('');
  lines.push('export const THEME_ASSETS: Record<string, ThemeAssetSource> = {');
  for (const { themeName, fileName, width, height } of entries) {
    lines.push(`  '${themeName}/${fileName}': {`);
    lines.push(`    source: require('${requirePath(themeName, fileName)}'),`);
    lines.push(`    width: ${width},`);
    lines.push(`    height: ${height},`);
    lines.push('  },');
  }
  lines.push('};');
  lines.push('');
  writeFileSync(registryPath, lines.join('\n'), 'utf8');

  console.log(`wrote ${entries.length} entries to ${registryPath}`);
  for (const themeName of themes) {
    const count = entries.filter((entry) => entry.themeName === themeName).length;
    console.log(`  ${themeName}: ${count} registry entries`);
  }
  if (entries.length === 0) {
    throw new Error('no theme PNGs found — registry would be empty');
  }
}

main();
